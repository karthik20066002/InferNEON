#!/usr/bin/env python3
"""gen_prompt.py — regenerate src/prompt.rs from token ids, then rebuild.

Usage:
    tools/gen_prompt.py 510,8467,310,4797
    tools/gen_prompt.py --file prompts.txt   # one id per line

The prompt is a const array in the firmware (no input path on bare metal),
so changing it means a rebuild. That is deliberate: it keeps the image
untouched and makes the prompt part of the build provenance.
"""
import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument('ids', nargs='?', help='comma-separated token ids')
    ap.add_argument('--file', help='file with one token id per line')
    ap.add_argument('--max-len', type=int, default=96,
                    help='truncate prompt to this many tokens (KV budget)')
    args = ap.parse_args()

    if args.file:
        ids = [int(x) for x in Path(args.file).read_text().split()]
    elif args.ids:
        ids = [int(x) for x in args.ids.split(',')]
    else:
        ap.error('need ids or --file')

    if len(ids) > args.max_len:
        print(f'truncating prompt {len(ids)} -> {args.max_len} tokens', file=sys.stderr)
        ids = ids[:args.max_len]
    if not ids:
        sys.exit('empty prompt')

    arr = ', '.join(str(i) for i in ids)
    out = (
        '//! prompt.rs — generated by tools/gen_prompt.py. Do not edit by hand.\n'
        '//! A run is a rebuild (not an image repack) because the prompt is baked in as\n'
        '//! a const array: the kernel has no input path, and adding one would be a\n'
        '//! whole feature for a test harness. `just build` after regenerating.\n\n'
        f'/// Token ids of the prompt under test (OLMoE tokenizer).\n'
        f'/// {len(ids)} tokens.\n'
        f'pub const PROMPT_IDS: [u32; {len(ids)}] = [{arr}];\n'
        f'pub const PROMPT_LEN: usize = {len(ids)};\n'
    )
    (ROOT / 'src/prompt.rs').write_text(out)
    print(f'wrote src/prompt.rs: {len(ids)} tokens', file=sys.stderr)

    r = subprocess.run(['just', 'build'], cwd=ROOT, capture_output=True, text=True)
    sys.stderr.write(r.stdout[-2000:])
    if r.returncode != 0:
        sys.stderr.write(r.stderr[-3000:])
        sys.exit(r.returncode)
    print('build ok', file=sys.stderr)


if __name__ == '__main__':
    main()
